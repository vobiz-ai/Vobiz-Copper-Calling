// Preloaded into the backend under test (node -r). Replaces global fetch so no
// request leaves the machine, and records every attempted request to a JSONL
// file so tests can assert on what the server tried to send, and where.
//
// Vobiz: two accounts with obvious fake values. Behaviours copied from the
// real API on purpose:
//  - POST /Endpoint/ rewrites the submitted username;
//  - app ids are 17 digits and come back UNQUOTED, so a server that runs them
//    through JSON.parse/Number gets the wrong id;
//  - MA_TEST0001 binds on {"app_id":"<string>"}; MA_TEST0002 ignores that and
//    only honours {"application": <integer>}.
//  - POST /JWT/Token/ signs access-token claims, refusing a wrong iss or a
//    lifetime outside 180..86400 s.
//
// Copper: two accounts, following Copper's Developer API reference:
//  - OAuth: POST app.copper.com/oauth/token (form-encoded, with the client
//    secret) returns an access token that never expires, and no refresh token;
//  - API keys arrive as X-PW-AccessToken + X-PW-Application: developer_api +
//    X-PW-UserEmail, and the email must be the key owner's;
//  - GET /users/me and GET /account say who and where;
//  - POST /{people,leads,companies}/search with phone_number {value, match:
//    "partial"} returns records whose number ENDS in those digits;
//  - the "Phone Call" activity type id differs per account;
//  - ids are integers.
// User 102's first search gets a 429 with Retry-After, which exercises the
// wait-and-retry.
